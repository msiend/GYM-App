const starterExercises: Exercise[] = rows.map(
  ([id, name, muscle, secondary, equipment, pattern, start, execution]) => ({
    id,
    name,
    muscle,
    secondary: secondary.split(","),
    equipment,
    pattern,
    category:
      pattern === "Isolation"
        ? "Isolation"
        : pattern === "Cardio"
          ? "Cardio"
          : pattern === "Mobility" || pattern === "Stretching"
            ? pattern
            : "Compound",
    difficulty: "Beginner",
    instructions: [start, execution],
    breathing:
      pattern === "Core"
        ? "Breathe normally throughout the hold."
        : "Exhale during the effort; inhale during the return. Avoid holding your breath.",
    mistakes:
      "Rushing repetitions, using momentum, or continuing after technique breaks down.",
    safety:
      "Use a comfortable range and a conservative load. Stop for pain, dizziness or unusual breathlessness.",
    alternatives: rows
      .filter((r) => r[5] === pattern && r[0] !== id)
      .map((r) => r[0]),
  }),
);
export const exercises: Exercise[] = [
  ...starterExercises.map((e) => ({
    ...e,
    tracking: e.id === "plank" ? ("seconds" as const) : ("reps" as const),
  })),
  ...(additional as Exercise[]),
];
export const exerciseById = (id: string) => exercises.find((e) => e.id === id)!;
